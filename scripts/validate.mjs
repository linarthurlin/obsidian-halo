import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import postcss from 'postcss';
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const component = JSON.parse(await readFile('component.json', 'utf8'));
const manifest = JSON.parse(await readFile('dist/theme/manifest.json', 'utf8'));
assert.equal(component.kind, 'theme');
assert.equal(manifest.version, pkg.version);
assert(manifest.name && manifest.minAppVersion && manifest.author);
assert(!('id' in manifest), 'Theme manifest must not identify a plugin');
const css = await readFile('dist/theme/theme.css', 'utf8');
postcss.parse(css);
assert(!/@import\b|https?:\/\//i.test(css), 'Offline styles only');
assert(!/\\n/.test(css), 'CSS modules must be joined with real newlines');
assert(css.includes('--pg-surface') && css.includes('forced-colors'));
console.log('Validated theme-only manifest and offline CSS.');
